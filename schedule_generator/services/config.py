"""Параметры генерации: значения по умолчанию и веса целевой функции.

Все «магические числа» алгоритма собраны здесь — чтобы тюнинг не требовал
правки логики и был виден в одном месте.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class SolverConfig:
    """Настройки решателя CP-SAT (можно переопределить на входе сервиса)."""

    time_limit_seconds: int = 30
    seed: int = 17
    num_search_workers: int = 8


# Полнота размещения всегда важнее мягких штрафов; масштаб задаёт objective.
WINDOW_FREE_MINUTES = 30           # обычный перерыв не считается окном
PENALTY_WINDOW = 1                 # за минуту ожидания сверх перерыва на человека
PENALTY_TEACHER_OVERLOAD = 60       # за пару сверх дневного лимита преподавателя
# --- Забота о людях (подробно — docs/SCHEDULING_RULES.md) ---
# Индекс усталости дня: см. services/wellbeing.py
FATIGUE_PAIR_WEIGHT = 10            # вклад каждой пары в усталость дня
FATIGUE_EARLY_WEIGHT = 5            # добавка, если день начинается с ранней пары
FATIGUE_LATE_WEIGHT = 5             # добавка за каждую позднюю пару
EARLY_LESSON_NUMBER = 1             # «ранняя» пара: номер <= этого значения
LATE_LESSON_NUMBER = 6              # «поздняя» пара: номер >= этого значения
FATIGUE_COMFORT_LEVEL = 40          # выше этого уровня день штрафуется
PENALTY_FATIGUE_EXCESS = 2          # штраф за единицу усталости выше комфортного
PENALTY_FATIGUE_PEAK = 1            # штраф за единицу самого тяжёлого дня
# Хронотип преподавателя
CHRONOTYPE_EARLY_BAD_FROM = 5       # жаворонку неудобны пары с этого номера
CHRONOTYPE_LATE_BAD_UNTIL = 2       # сове неудобны пары до этого номера включительно
PENALTY_CHRONOTYPE = 2              # штраф за пару не в своё время
# Режим подготовки к сессии
PENALTY_FREE_DAY_VIOLATION = 30     # штраф за день сверх допустимого
# Дорога между локациями: в стольких слотах после пары участник не может
# быть на другой локации (0 — правило отключено)
TRAVEL_BUFFER_SLOTS = 1
# Перепланирование: бонус за сохранение пары (слота и аудитории) без изменений.
# Больше награды за пару, чтобы сохранение перевешивало любой выигрыш по мягким штрафам.
PIN_BONUS = 1000


@dataclass(frozen=True)
class PlanningPreferences:
    """Параметры запуска, меняющие мягкие правила (не веса, а режимы)."""

    free_days_per_group: int = 0    # режим подготовки к сессии; 0 — выключен
